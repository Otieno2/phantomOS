#!/bin/bash
# gen-package-lists.sh — turn manifests/*.pkgs into live/config/package-lists/*.list.chroot.
#
# The manifests are the single source of truth (and §5 is the source of truth for the
# manifests). The generated lists are build output and are gitignored; committing them
# would leave two places in the tree that can disagree.
#
# Why the comment stripping matters: live-build hands each surviving line to apt, so a
# trailing "# §6.7" on a package line is not a comment to apt. manifests/*.pkgs are
# annotated for humans, so this script is the only thing allowed to read them.
#
# Usage: scripts/gen-package-lists.sh [repo-root]

set -euo pipefail

ROOT="${1:-$(cd "$(dirname "$0")/.." && pwd)}"
OUT="$ROOT/live/config/package-lists"
mkdir -p "$OUT"
rm -f "$OUT"/*.list.chroot

# write_list <list-name> <provenance-line> <package lines on stdin>
write_list() {
	local name="$1" prov="$2" out="$OUT/$1.list.chroot"
	{
		echo "# GENERATED by scripts/gen-package-lists.sh — edit the manifests instead."
		echo "# $prov"
		sed -e 's/#.*//' | awk 'NF' | sed -e 's/[[:space:]]*$//'
	} > "$out"
	printf '%3d entries -> %s\n' "$(grep -vc '^#' "$out")" "$name.list.chroot"
}

# Our own metapackages. §4.2: base and desktop are always installed together in the
# shipped image, so both are named even though desktop Depends on base.
printf 'phantomos-base\nphantomos-desktop\n' | \
	write_list phantomos "our metapackages, §4.2; built by scripts/build-packages.sh"

# The live system itself, not §5 inventory (see the header of manifests/live.pkgs).
cat "$ROOT/manifests/live.pkgs" | \
	write_list live "manifests/live.pkgs"
